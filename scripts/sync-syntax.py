#!/usr/bin/env python3
"""Derive Quarto Live syntax variables from the synced rtemis palettes."""

import json
from pathlib import Path

source = Path(__file__).resolve().parents[1] / "theme"
destination = source

roles = {
    "al": "Alert", "an": "Annotation", "at": "Attribute", "bn": "BaseN",
    "bu": "BuiltIn", "ch": "Char", "co": "Comment", "cv": "CommentVar",
    "cn": "Constant", "cf": "ControlFlow", "dt": "DataType", "dv": "DecVal",
    "do": "Documentation", "er": "Error", "ex": "Extension", "fl": "Float",
    "fu": "Function", "im": "Import", "in": "Information", "kw": "Keyword",
    "op": "Operator", "ot": "Other", "pp": "Preprocessor", "re": "RegionMarker",
    "sc": "SpecialChar", "ss": "SpecialString", "st": "String",
    "va": "Variable", "vs": "VerbatimString", "wa": "Warning",
}
css = ["/* Generated by scripts/sync-syntax.py from the rtemis Quarto palettes. */"]
for mode in ("light", "dark"):
    palette = json.loads((source / f"rtemis-{mode}.theme").read_text())
    styles = palette["text-styles"]
    css.append(f".quarto-{mode} {{")
    for name, value in {
        "code-bg": palette["background-color"],
        "code-fg": palette["text-color"],
        "code-line-number": palette["line-number-color"],
        "code-comment": styles["Comment"]["text-color"],
        "code-operator": styles["Operator"]["text-color"],
        "code-string": styles["String"]["text-color"],
        "code-error": styles["Error"]["text-color"],
        "bs-code-color": palette["text-color"],
    }.items():
        css.append(f"    --{name}: {value};")
    for token, role in roles.items():
        css.append(f"    --exercise-editor-hl-{token}: {styles[role]['text-color']};")
    css.append("}")

destination.mkdir(parents=True, exist_ok=True)
target = destination / "rtemis-syntax.css"
content = "\n".join(css) + "\n"
if not target.exists() or target.read_text() != content:
    target.write_text(content)
